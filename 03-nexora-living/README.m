# NEXORA LIVING

## Proyecto residencial

Nexora Living desarrolla nuevos modelos de vivienda basados en soluciones modulares, eficiencia, comunidad y flexibilidad residencial.

## Ubicación

Proyecto orientado al entorno del Mar Menor, entre San Javier y San Pedro del Pinatar, Región de Murcia.

## Modelo

- Viviendas modulares totalmente equipadas
- Diseño funcional y mediterráneo
- Espacios privados y zonas comunes
- Modelo de alquiler con opción de compra
- Proyecto orientado a nuevos perfiles residenciales

## Fase piloto

Primera fase prevista como proyecto piloto para validar el modelo y su aceptación en el mercado.

## Objetivo

Desarrollar un modelo residencial innovador, escalable y atractivo para residentes e inversores.

